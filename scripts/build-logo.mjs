#!/usr/bin/env node
// Builds the Equal AI logo for both platforms from the official vector (no tracing).
//   input : tokens/brand/equal-logo.svg   (official "EQUAL AI LOGO _BLACK.svg", 113 × 24, single colour)
//   output: web/src/foundations/logo.ts
//           compose/equal-ds/src/main/java/ai/equal/ds/icons/EqualLogoVectors.kt
// The first two paths are the six-dot mark; the rest are the "equal ai" wordmark. Run: npm run logo

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const svg = readFileSync(resolve(root, 'tokens/brand/equal-logo.svg'), 'utf8');
const [, W, H] = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/).map(Number);
const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
if (paths.length < 3) throw new Error('expected the mark (2 paths) + wordmark paths');
const mark = paths.slice(0, 2).join('');
const word = paths.slice(2).join('');
// Bounds from the coordinates: mark right edge, wordmark left edge.
const xs = (d) => [...d.matchAll(/(-?\d*\.?\d+)[ ,](-?\d*\.?\d+)/g)].map((m) => Number(m[1]));
const MARK_W = Math.max(...xs(mark));
const WORD_X = Math.min(...xs(word));
const r = (n) => Math.round(n * 1000) / 1000;

writeFileSync(
  resolve(root, 'web/src/foundations/logo.ts'),
  `// GENERATED by scripts/build-logo.mjs from tokens/brand/equal-logo.svg (official vector). Do not edit.
// Coordinate space: the full lockup is ${W} x ${H}. The six-dot mark occupies x 0-${r(MARK_W)}; the wordmark x ${r(WORD_X)}-${W}.

export const LOGO_VIEWBOX = { width: ${W}, height: ${H} } as const;
export const MARK_VIEWBOX = { width: ${r(MARK_W)}, height: ${H} } as const;
/** Where the wordmark starts (for the wordmark-only variant). */
export const WORDMARK_X = ${r(WORD_X)};

/** Six-dot mark. */
export const MARK_PATH = ${JSON.stringify(mark)};

/** "equal ai" wordmark. */
export const WORDMARK_PATH = ${JSON.stringify(word)};
`,
);

writeFileSync(
  resolve(root, 'compose/equal-ds/src/main/java/ai/equal/ds/icons/EqualLogoVectors.kt'),
  `// GENERATED by scripts/build-logo.mjs from tokens/brand/equal-logo.svg (official vector). Do not edit.
package ai.equal.ds.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** Vector paths of the official Equal AI logo. Full lockup viewport ${W} x ${H}; mark x 0-${r(MARK_W)}. */
object EqualLogoPaths {
    const val MARK = ${JSON.stringify(mark)}
    const val WORDMARK = ${JSON.stringify(word)}
    const val WIDTH = ${W}f
    const val HEIGHT = ${H}f
    const val MARK_WIDTH = ${r(MARK_W)}f
    const val WORDMARK_X = ${r(WORD_X)}f
}

/**
 * Builds the logo as an ImageVector tinted with [color]. Use with Icon/Image and \`tint = Color.Unspecified\`.
 * [variant]: FULL = mark + wordmark, MARK = six dots, WORDMARK = "equal ai".
 */
enum class EqualLogoVariant { FULL, MARK, WORDMARK }

fun equalLogoVector(color: Color, variant: EqualLogoVariant = EqualLogoVariant.FULL): ImageVector {
    val x0 = if (variant == EqualLogoVariant.WORDMARK) EqualLogoPaths.WORDMARK_X else 0f
    val w = if (variant == EqualLogoVariant.MARK) EqualLogoPaths.MARK_WIDTH else EqualLogoPaths.WIDTH - x0
    val b = ImageVector.Builder(
        name = "EqualLogo_$variant",
        defaultWidth = w.dp,
        defaultHeight = EqualLogoPaths.HEIGHT.dp,
        viewportWidth = w,
        viewportHeight = EqualLogoPaths.HEIGHT,
    )
    // Shift the wordmark-only variant left so it starts at x = 0.
    b.addGroup(translationX = -x0)
    if (variant != EqualLogoVariant.WORDMARK) b.addPath(pathData = addPathNodes(EqualLogoPaths.MARK), fill = SolidColor(color))
    if (variant != EqualLogoVariant.MARK) b.addPath(pathData = addPathNodes(EqualLogoPaths.WORDMARK), fill = SolidColor(color))
    b.clearGroup()
    return b.build()
}
`,
);
console.log(`  wrote logo.ts + EqualLogoVectors.kt (${W} x ${H}, mark 0-${r(MARK_W)}, wordmark from ${r(WORD_X)})`);
